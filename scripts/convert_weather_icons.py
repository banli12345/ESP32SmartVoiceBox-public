"""Convert the supplied Seniverse white weather icons to built-in LVGL v8 images."""
from pathlib import Path
import argparse,zipfile,hashlib,json,io
from PIL import Image,ImageOps

ROOT=Path(__file__).resolve().parents[1]
CODES=tuple(range(39))+(99,)

def generate(assets:Path,output:Path):
    rows=[]
    for code in CODES:
        with Image.open(assets/(str(code)+'.png'))as source:
            source=source.convert('RGBA')
            tile=Image.new('RGBA',(64,64))
            icon=ImageOps.contain(source,(56,56),Image.Resampling.LANCZOS)
            tile.alpha_composite(icon,((64-icon.width)//2,(64-icon.height)//2))
        raw=bytearray()
        for r,g,b,a in tile.get_flattened_data()if hasattr(tile,'get_flattened_data')else tile.getdata():
            v=((r>>3)<<11)|((g>>2)<<5)|(b>>3);raw.extend((v&255,v>>8,a))
        rows.append((code,raw))
    out=['/* Generated by scripts/convert_weather_icons.py; RGB565 little-endian + alpha. */','#include "WeatherIcons.h"','']
    for code,raw in rows:
        out.append('static const LV_ATTRIBUTE_MEM_ALIGN uint8_t pixels_'+str(code)+'[] = {')
        out.extend('    '+','.join('0x%02x'%x for x in raw[i:i+24])+','for i in range(0,len(raw),24))
        out.append('};')
    out.append('const lv_img_dsc_t weather_icon_descriptors[40] = {')
    for code,raw in rows:
        out.append('    { .header = { .cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .w = 64, .h = 64 }, .data_size = '+str(len(raw))+', .data = pixels_'+str(code)+' },')
    out.append('};\n');output.write_text('\n'.join(out),encoding='utf-8')
    print('Generated 40 weather icons, 64x64 RGB565+alpha,',sum(len(r)for _,r in rows),'pixel bytes')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source-zip',type=Path)
    p.add_argument('--assets',type=Path,default=ROOT/'assets/weather_icons/white')
    p.add_argument('--output',type=Path,default=ROOT/'src/WeatherIconsData.c')
    a=p.parse_args();a.assets.mkdir(parents=True,exist_ok=True)
    if a.source_zip:
        meta={'source':'User-provided Seniverse white weather icon set','zip_file':a.source_zip.name,'zip_sha256':hashlib.sha256(a.source_zip.read_bytes()).hexdigest(),'codes':list(CODES),'files':[]}
        with zipfile.ZipFile(a.source_zip)as z:
            for code in CODES:
                data=z.read('white/'+str(code)+'@2x.png')
                with Image.open(io.BytesIO(data))as im:dimensions=list(im.size)
                dest=a.assets/(str(code)+'.png');dest.write_bytes(data)
                meta['files'].append({'file':dest.name,'sha256':hashlib.sha256(data).hexdigest(),'dimensions':dimensions})
        (a.assets.parent/'source.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2),encoding='utf-8')
    generate(a.assets,a.output)

if __name__=='__main__':main()

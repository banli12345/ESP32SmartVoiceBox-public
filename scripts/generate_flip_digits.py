"""Derive the clock's eleven 72px glyphs from bundled LVGL Montserrat 48.
No external fonts or runtime scaling buffer. Re-run after a font source update.
"""
from pathlib import Path
import re,math
ROOT=Path(__file__).resolve().parents[1]
source=(ROOT/'components/lvgl/src/font/lv_font_montserrat_48.c').read_text(encoding='utf-8')
block=source.split('const uint8_t glyph_bitmap[] = {',1)[1].split('};',1)[0]
block=re.sub(r'/\*.*?\*/','',block,flags=re.S)
bitmap=bytes(int(x,16) for x in re.findall(r'0x([0-9a-fA-F]+)',block))
block=source.split('glyph_dsc[] = {',1)[1].split('};',1)[0]
fields=('bitmap_index','adv_w','box_w','box_h','ofs_x','ofs_y')
descriptors=[dict(zip(fields,map(int,m))) for m in re.findall(r'\.bitmap_index = (-?\d+), \.adv_w = (-?\d+), \.box_w = (-?\d+), \.box_h = (-?\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)',block)]
result=bytearray();out=[dict(zip(fields,(0,0,0,0,0,0)))];scale=1.5
for ch in '-0123456789':
 glyph=descriptors[ord(ch)-32+1];w,h=glyph['box_w'],glyph['box_h'];start=glyph['bitmap_index']
 samples=[]
 for i in range(w*h):samples.append((bitmap[start+i//2] >> (4 if i%2==0 else 0))&15)
 nw,nh=round(w*scale),round(h*scale);pixels=[]
 for y in range(nh):
  sy=max(0,min(h-1,(y+.5)/scale-.5));y0=int(sy);fy=sy-y0;y1=min(h-1,y0+1)
  for x in range(nw):
   sx=max(0,min(w-1,(x+.5)/scale-.5));x0=int(sx);fx=sx-x0;x1=min(w-1,x0+1)
   top=samples[y0*w+x0]*(1-fx)+samples[y0*w+x1]*fx
   bottom=samples[y1*w+x0]*(1-fx)+samples[y1*w+x1]*fx
   pixels.append(round(top*(1-fy)+bottom*fy))
 out.append(dict(zip(fields,(len(result),48*16,nw,nh,(48-nw)//2,round(glyph['ofs_y']*scale)))))
 if len(pixels)%2:pixels.append(0)
 result.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
text='''/* Generated by scripts/generate_flip_digits.py from LVGL Montserrat 48.
 * Numeric-only 72px derivative; source/license: components/lvgl/LICENCE.txt.
 * Eleven glyphs in flash, no runtime scaling buffers or external font files.
 */
#include "lvgl.h"
static const uint8_t bitmap[] = {\n'''
for i in range(0,len(result),20):text+='    '+','.join(f'0x{v:02x}' for v in result[i:i+20])+',\n'
text+='};\nstatic const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {\n'
for glyph in out:text+='    {'+', '.join(f'.{key} = {glyph[key]}' for key in fields)+'},\n'
text+='''};
static const lv_font_fmt_txt_cmap_t maps[] = {
    {.range_start=45,.range_length=1,.glyph_id_start=1,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start=48,.range_length=10,.glyph_id_start=2,.type=LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}
};
static lv_font_fmt_txt_glyph_cache_t cache;
static lv_font_fmt_txt_dsc_t descriptor = {
    .glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=maps,.cmap_num=2,.bpp=4,.bitmap_format=0,.cache=&cache
};
const lv_font_t lv_font_flip_digits_72 = {
    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,
    .line_height=78,.base_line=14,.subpx=LV_FONT_SUBPX_NONE,.dsc=&descriptor
};
'''
p=ROOT/'src/flip_digits_72.c';p.write_text(text,encoding='utf-8');print('Generated eleven flash glyphs:',len(result),'bitmap bytes')

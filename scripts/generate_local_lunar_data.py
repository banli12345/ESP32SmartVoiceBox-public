"""Compile HKO 1901-2099 conversion tables into compact offline lookup data.

Source: https://www.hko.gov.hk/tc/gts/time/conversion.htm
Downloads happen on the development computer, never on the ESP32.
"""
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor, as_completed
import datetime as dt
import hashlib
import json
import re
import time
import requests

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT/'.tools/lunar-life-20261114/hko'
TERMS = '小寒 大寒 立春 雨水 惊蛰 春分 清明 谷雨 立夏 小满 芒种 夏至 小暑 大暑 立秋 处暑 白露 秋分 寒露 霜降 立冬 小雪 大雪 冬至'.split()
TRANS = str.maketrans({'驚':'惊','蟄':'蛰','穀':'谷','滿':'满','處':'处','閏':'闰'})
NUMBERS = ['','一','二','三','四','五','六','七','八','九','十','十一','十二']
DAYS = ['初一','初二','初三','初四','初五','初六','初七','初八','初九','初十',
        '十一','十二','十三','十四','十五','十六','十七','十八','十九','二十',
        '廿一','廿二','廿三','廿四','廿五','廿六','廿七','廿八','廿九','三十']


def obtain(year):
    path = CACHE/f'{year}.txt'
    if path.exists():
        return path
    url = f'https://www.hko.gov.hk/tc/gts/time/calendar/text/files/T{year}c.txt'
    for attempt in range(3):
        try:
            response = requests.get(url, timeout=30)
            response.raise_for_status()
            text = response.content.decode('utf-8-sig')
            assert f'{year}年' in text
            path.write_bytes(response.content)
            return path
        except (requests.RequestException, UnicodeError, AssertionError):
            if attempt == 2:
                raise
            time.sleep(1)


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    years = range(1901, 2100)
    with ThreadPoolExecutor(max_workers=4) as pool:
        for future in as_completed([pool.submit(obtain, year) for year in years]):
            future.result()
    epoch = dt.date(1901, 1, 1)
    lunar_year, lunar_month, leap = 1900, 11, False
    starts = [(0, lunar_year, lunar_month, leap)]
    term_days, facts, manifest, repaired_names = [], [], [], []
    previous_day = 10
    pattern = re.compile(r'^(\d{4})年(\d{1,2})月(\d{1,2})日\s+(\S+)\s+星期[一二三四五六日天]\s*(\S*)')
    for year in years:
        path = CACHE/f'{year}.txt'
        raw = path.read_bytes()
        rows = []
        terms = [0]*24
        for line in raw.decode('utf-8-sig').splitlines():
            match = pattern.match(line.strip())
            if not match:
                continue
            y, m, d = map(int, match.group(1, 2, 3))
            date = dt.date(y, m, d)
            assert y == year
            lunar, term = (s.translate(TRANS) for s in match.group(4, 5))
            if lunar.endswith('月'):
                assert previous_day in (29, 30), (date, previous_day)
                leap = lunar.startswith('闰')
                name = lunar.removeprefix('闰')[:-1]
                lunar_month = 1 if name == '正' else NUMBERS.index(name)
                if lunar_month == 1 and not leap:
                    lunar_year = year
                lunar_day = 1
                starts.append(((date-epoch).days, lunar_year, lunar_month, leap))
            else:
                lunar_day = DAYS.index(lunar)+1
                assert lunar_day == previous_day+1, (date, previous_day, lunar_day)
            previous_day = lunar_day
            if term:
                # Some old HKO text files have mojibake in the term NAME.
                # Keep the published date; names follow the fixed two/month order.
                index = (m-1)*2 + (1 if terms[(m-1)*2] else 0)
                if term in TERMS:
                    assert TERMS.index(term) == index, (date, term)
                else:
                    repaired_names.append({'date':date.isoformat(),'source_name':term,'term':TERMS[index]})
                term = TERMS[index]
                assert m == index//2+1 and terms[index] == 0, (date, term)
                terms[index] = d
            rows.append(date)
            facts.append([date.isoformat(), lunar_year, lunar_month, lunar_day, int(leap), term])
        expected = (dt.date(year+1, 1, 1)-dt.date(year, 1, 1)).days
        assert len(rows) == expected
        assert rows == [dt.date(year, 1, 1)+dt.timedelta(days=i) for i in range(expected)]
        assert all(terms), (year, terms)
        term_days.append(terms)
        manifest.append({'year':year,'sha256':hashlib.sha256(raw).hexdigest()})
    packed = [offset | ((year-1900)<<17) | (month<<25) | (int(leap)<<29) for offset,year,month,leap in starts]
    assert all(0 <= n < (1 << 30) for n in packed)
    output = ['/* Generated by scripts/generate_local_lunar_data.py.',
              ' * Source: Hong Kong Observatory Gregorian-Lunar Conversion Tables, 1901-2099.',
              ' * https://www.hko.gov.hk/tc/gts/time/conversion.htm',
              ' * The first record starts at lunar 1900-11-11 on Gregorian 1901-01-01.',
              ' */', 'static const uint32_t lunar_month_starts[] = {']
    for i in range(0, len(packed), 8):
        output.append('    '+', '.join(f'0x{x:08x}U' for x in packed[i:i+8])+',')
    output += ['};', 'static const uint8_t solar_term_days[199][24] = {']
    for year, terms in zip(years, term_days):
        output.append('    {'+', '.join(map(str, terms))+'}, /* '+str(year)+' */')
    output += ['};', '']
    (ROOT/'src/LocalLunarData.inc').write_text('\n'.join(output), encoding='utf-8')
    (CACHE/'manifest.json').write_text(json.dumps(manifest,indent=2), encoding='utf-8')
    (CACHE/'repaired-term-names.json').write_text(json.dumps(repaired_names,ensure_ascii=False,indent=2),encoding='utf-8')
    (CACHE/'reference-days.json').write_text(json.dumps(facts,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
    print(f'Generated {len(starts)} lunar month starts and {len(facts)} reference days; {len(packed)*4+199*24} data bytes')


if __name__ == '__main__':
    main()
